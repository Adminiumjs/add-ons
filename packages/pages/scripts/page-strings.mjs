/**
 * The screens' English, gathered from where it is written.
 *
 * Every sentence a screen shows is written once, beside the call that shows
 * it: `t('list.title', 'Landing pages')`. This reads those calls and
 * writes `src/pages/strings/en-US.ts`, one object per section (a key's first
 * word), so the file the other languages are translated from can never say
 * something the screen does not. `--check` writes nothing and fails when the
 * file is behind; `src/pages/strings.test.ts` runs the same comparison.
 *
 * A section may live in a file of its own (`OWN_FILES`): the editor's words
 * are `src/pages/strings/editor/en-US.ts`, and `en-US.ts` takes them from
 * there by one line, so the editor and the other screens never write into the
 * same file.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const SECTIONS = ['shared', 'list', 'funnels', 'editor'];
const here = dirname(fileURLToPath(import.meta.url));
export const PAGES = resolve(here, '../src/pages');
export const TARGET = join(PAGES, 'strings/en-US.ts');
/** The sections kept in a file of their own, by the path under `strings/` that holds their English. */
export const OWN_FILES = { editor: 'editor/en-US.ts' };

function sources(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return entry.name === 'strings' || entry.name === 'testing' ? [] : sources(path);
    return /\.tsx?$/.test(entry.name) && !/\.test\.tsx?$/.test(entry.name) ? [path] : [];
  });
}

const CALL = /\bt\(\s*'([A-Za-z0-9_.-]+)',\s*('(?:[^'\\\n]|\\.)*'|"(?:[^"\\\n]|\\.)*")/g;

/** Every key with its English, by section; throws on a key written with two different sentences. */
export function gather() {
  const found = new Map();
  for (const file of sources(PAGES)) {
    const text = readFileSync(file, 'utf8');
    for (const match of text.matchAll(CALL)) {
      const key = match[1];
      const words = new Function(`return ${match[2]}`)();
      const section = key.split('.')[0];
      if (!SECTIONS.includes(section)) throw new Error(`${file}: "${key}" belongs to no section (${SECTIONS.join(', ')})`);
      if (found.has(key) && found.get(key) !== words) throw new Error(`"${key}" is written with two sentences:\n  ${found.get(key)}\n  ${words}`);
      found.set(key, words);
    }
  }
  return Object.fromEntries(SECTIONS.map((section) => [section, Object.fromEntries([...found].filter(([key]) => key.split('.')[0] === section).sort(([a], [b]) => (a < b ? -1 : 1)))]));
}

const constOf = (section, words) => `export const ${section}: Readonly<Record<string, string>> = ${JSON.stringify(words, null, 2)};`;

export function render(sections) {
  const body = SECTIONS.map((section) => (OWN_FILES[section] === undefined ? constOf(section, sections[section]) : `export { ${section} } from './${OWN_FILES[section]}';`)).join('\n\n');
  return `/** GENERATED by scripts/page-strings.mjs from the sentences written in the screens. Do not edit by hand. */\n${body}\n`;
}

/** Each section kept in a file of its own, as `{ path, text }`. */
export function renderOwn(sections) {
  return Object.entries(OWN_FILES).map(([section, path]) => ({ path: join(PAGES, 'strings', path), text: `/** GENERATED by scripts/page-strings.mjs from the sentences written in the screens. Do not edit by hand. */\n${constOf(section, sections[section])}\n` }));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const sections = gather();
  const files = [{ path: TARGET, text: render(sections) }, ...renderOwn(sections)];
  if (process.argv.includes('--check')) {
    for (const file of files) {
      if (readFileSync(file.path, 'utf8') !== file.text) {
        console.error(`${file.path} is behind the screens: run \`node scripts/page-strings.mjs\`.`);
        process.exit(1);
      }
    }
  } else for (const file of files) writeFileSync(file.path, file.text);
}
